$set = static function (array &$data, string $path, string $value): void {
    $parts = explode('.', $path);
    $cursor =& $data;
    foreach ($parts as $part) {
        $key = ctype_digit($part) ? (int) $part : $part;
        if (!is_array($cursor) || !array_key_exists($key, $cursor)) throw new RuntimeException('Unknown language path: ' . $path);
        $cursor =& $cursor[$key];
    }
    if (!is_string($cursor)) throw new RuntimeException('Language path is not a string: ' . $path);
    $cursor = $value;
};
$clean = static function (&$value) use (&$clean): void {
    if (is_array($value)) {
        foreach ($value as &$item) $clean($item);
        return;
    }
    if (!is_string($value)) return;
    $value = preg_replace('/[\x{200B}-\x{200F}\x{202A}-\x{202E}\x{2060}-\x{206F}\x{FEFF}]/u', '', $value) ?? $value;
    $value = str_replace('—', '-', $value);
};

foreach ($updates as $locale => $changes) {
    $file = $root . '/lang/' . $locale . '.json';
    $data = json_decode((string) file_get_contents($file), true, 512, JSON_THROW_ON_ERROR);
    foreach ($changes as $path => $value) $set($data, $path, $value);
    $clean($data);
    $encoded = json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
    if (file_put_contents($file, $encoded . PHP_EOL, LOCK_EX) === false) throw new RuntimeException('Cannot write ' . $file);
    echo $locale . ': ' . count($changes) . " editorial changes\n";
}
